const { OUT, launchBrowser, emulatorContext, clearEmulators } = require('../harness');
const B = 'http://127.0.0.1:8126';
let fails = 0;
const check = (label, got, want) => { const ok = JSON.stringify(got) === JSON.stringify(want); if (!ok) fails++; console.log(`${ok ? 'PASS' : 'FAIL'} ${label}: ${JSON.stringify(got)}${ok ? '' : ` (wanted ${JSON.stringify(want)})`}`); };
const codes = async (email, type) => (await (await fetch('http://127.0.0.1:9099/emulator/v1/projects/daily-reports-test/oobCodes')).json()).oobCodes.filter((c) => c.email === email && c.requestType === type).map((c) => c.oobCode);
(async () => {
  await clearEmulators();
  const browser = await launchBrowser();
  const errs = [];
  for (const dev of [{ viewport: { width: 1280, height: 900 } }, { viewport: { width: 390, height: 844 } }]) {
    const tag = dev.viewport.width > 500 ? 'desktop' : 'phone';
    const email = `pat-${tag}@example.com`;
    const p = await (await emulatorContext(browser, dev)).newPage();
    p.on('pageerror', (e) => errs.push(e.message));
    await p.goto(`${B}/settings.html`); await p.waitForTimeout(800);
    await p.evaluate(async (email) => { await createAccount({ name: 'Pat', email, password: 'patpass12' }); await resendAccountVerification(); }, email);
    await p.waitForTimeout(800);
    const [verify] = await codes(email, 'VERIFY_EMAIL');
    await p.goto(`${B}/auth-action.html?mode=verifyEmail&oobCode=${verify}`);
    await p.waitForSelector('#view-done:not([hidden])', { timeout: 10000 });
    check(`${tag}: verify link confirms`, [await p.textContent('#done-title'), await p.evaluate(async () => (await getAccount()).emailVerified)], ['Email Verified', true]);
    await p.screenshot({ path: `${OUT}/authaction-${tag}-verified.png` });
    await p.goto(`${B}/auth-action.html?mode=verifyEmail&oobCode=${verify}`);
    await p.waitForSelector('#view-error:not([hidden])', { timeout: 10000 });
    check(`${tag}: used link explains itself`, (await p.textContent('#error-text')).startsWith('This link has already been used'), true);
    await p.evaluate(async (email) => { const { auth, authApi } = await waitForFirebaseCore(); await authApi.sendPasswordResetEmail(auth, email); }, email);
    await p.waitForTimeout(800);
    const [reset] = await codes(email, 'PASSWORD_RESET');
    await p.goto(`${B}/auth-action.html?mode=resetPassword&oobCode=${reset}`);
    await p.waitForSelector('#view-reset:not([hidden])', { timeout: 10000 });
    check(`${tag}: reset shows the email`, await p.textContent('#reset-email'), email);
    await p.fill('#reset-password', 'short'); await p.click('#btn-reset');
    check(`${tag}: short password refused`, await p.textContent('#reset-error'), 'Choose a password with at least 8 characters.');
    await p.fill('#reset-password', 'newpass123'); await p.fill('#reset-confirm', 'different1'); await p.click('#btn-reset');
    check(`${tag}: mismatch refused`, await p.textContent('#reset-error'), "The two passwords don't match.");
    await p.fill('#reset-confirm', 'newpass123'); await p.screenshot({ path: `${OUT}/authaction-${tag}-reset.png` });
    await p.click('#btn-reset');
    await p.waitForSelector('#view-done:not([hidden])', { timeout: 10000 });
    check(`${tag}: password changed`, await p.textContent('#done-title'), 'Password Changed');
    const q = await (await emulatorContext(browser, dev)).newPage();
    await q.goto(`${B}/login.html`); await q.waitForTimeout(800);
    check(`${tag}: new password signs in`, await q.evaluate((email) => signInAccount({ email, password: 'newpass123' }).then(() => 'ok', (e) => e.message), email), 'ok');
    const hscroll = await p.evaluate(() => document.documentElement.scrollWidth > window.innerWidth);
    check(`${tag}: no sideways scroll`, hscroll, false);
  }
  const p = await (await emulatorContext(browser)).newPage();
  await p.goto(`${B}/auth-action.html?mode=verifyEmail&oobCode=nonsense`);
  await p.waitForSelector('#view-error:not([hidden])', { timeout: 10000 });
  check('bad link explains itself', await p.isVisible('#view-error'), true);
  check('page errors', errs, []);
  console.log(fails ? `${fails} FAILED` : 'ALL PASSED');
  await browser.close();
})();
